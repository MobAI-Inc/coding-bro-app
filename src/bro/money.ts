/**
 * 钱的表示与显示。
 *
 * 全站只有这一个金额格式化函数，也只有这一种金额表示：**整数分**。
 *
 * 用浮点存美元会在最普通的运算上出错——`20 * 0.15` 得到的是
 * 3.0000000000000004，而这个数会一路流到「本月还能兑 $3.0000000000000004」
 * 里去。所以比例一律写成 `×15÷100` 这种整数乘除，浮点只允许出现在最后
 * 拼显示字符串的那一步，也就是这个文件。
 *
 * 积分页和 Plan 页都要显示金额。各写一份的话，迟早有一份会用除法实现，
 * 然后在某个金额上吐出 "$0.30000000000000004"——而且大概率是在另一份
 * 已经修好之后。放一处，测一处。
 */

/**
 * 整数分转美元显示，固定两位小数。
 *
 * 负号放在 `$` 前面：「-$1.20」是钱的写法，「$-1.20」不是。
 */
export function formatUsd(cents: number): string {
  const sign = cents < 0 ? "-" : "";
  const abs = Math.abs(cents);
  return `${sign}$${Math.floor(abs / 100)}.${String(abs % 100).padStart(2, "0")}`;
}
